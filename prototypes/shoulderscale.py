def shoulder_paint(model, pose):
    patch = PAINT[model][pose]
    if patch is None:
        return {}
    left, top, *rows = patch
    return {(left+x, top+y): int(tone) for y, row in enumerate(rows)
            for x, tone in enumerate(row) if tone != "."}


