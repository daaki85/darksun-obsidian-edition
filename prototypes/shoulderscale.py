def jerkin_facing(model, pose):
    patch = JERKIN_FACING.get((model, pose))
    if not patch:
        return {}
    left, top, *rows = patch
    leather = {"a": 89, "b": 92, "c": 94}
    return {(left+x, top+y): leather[tone] for y, row in enumerate(rows)
            for x, tone in enumerate(row) if tone != "."}
