def stamp(points):
    """Rasterize in local pose coordinates, including the trailing hem."""
    mask = Image.new("1", (60, 54))
    ImageDraw.Draw(mask).polygon([(x+6, y) for x, y in points], fill=1)
    return {(x-6, y) for y in range(mask.height) for x in range(mask.width) if mask.getpixel((x, y))}


