def fitted_panels(pose, female):
    bodice, short, long = PATTERNS[pose]
    if female:
        bodice = WOMAN_BODICE.get(pose, bodice)
    left, right = bodice[0], bodice[-1]
    # The front of the belt dips around the hip. Its back follows the
    # sacrum. Both skirt and strap finish on the very same sewn edge.
    belt = (left, ((left[0]+right[0])//2, (left[1]+right[1])//2+1), right)
    top = stamp((*bodice, belt[1]))
    wrap = stamp((*belt, *reversed(short)))
    robe = stamp((*belt, *reversed(long)))
    arm = stamp(ARMS[pose]) if pose in ARMS else set()
    hair = set()
    if female and pose in HAIR_EDGE:
        edge = HAIR_EDGE[pose]
        hair = stamp(((edge[0][0], 0), *edge, (edge[-1][0], 0)))
    if female and pose == 26:
        # A loose lock hangs from behind her outstretched bow arm.
        hair.update(stamp(((20, 15), (22, 16), (24, 17), (23, 18), (21, 20), (20, 20), (21, 17))))
    sleeve = set().union(*(stamp(panel) for panel in SLEEVES[pose]))
    # The split skirts of the leather jerkin hang at either hip. The
    # Gladiator's single wrap crosses the gap over the advancing thigh.
    flap = list(short)
    middle = len(flap)//2
    x, y = flap[middle]
    flap[middle] = x, max(belt[1][1]+1, y-2)
    for i in (1, len(flap)-2):
        x, y = flap[i]
        flap[i] = x, y+1
    jerkin = stamp((*belt, *reversed(flap)))
    # Keep the air between the forward wrist and the hip in profile step
    # one. The linen meets the far shin at a different angle in each stride.
    if pose == 11:
        for panel in (wrap, jerkin, robe):
            panel.difference_update({(x, y) for x, y in panel if x >= 11 and y <= 23})
    turned_hem = {6: ((18, 29),), 22: ((9, 29),), 23: ((15, 25), (16, 25)),
                  25: ((19, 35),), 26: ((24, 35), (25, 36))}
    robe.update(turned_hem.get(pose, ()))
    if pose == 8:
        jerkin.add((14, 28))
    return top, wrap, jerkin, robe, arm, hair, sleeve, belt


